Dict.translateText = function(s_str){
    return Dict.map[s_str];
};

Dict.translateObj_jQ = function(obj_jQ){
    var tit = obj_jQ.attr("title");
    if (Dict.map[tit]) {
        if (tit.match("btn"))
            obj_jQ.val(Dict.map[tit]);
        else
            obj_jQ.text(Dict.map[tit]);

        obj_jQ.removeAttr('title');
    } else {
        console.log("Can not translate ("+tit+")");
    }
};

Dict.translateAll = function(){
    var title_arr = document.querySelectorAll('[title]');
    for(var i=0; i<title_arr.length; i++)
    {
        var tit = title_arr[i].title;
        if(Dict.map[tit]) {
            if(tit.match("btn"))
                title_arr[i].value = Dict.map[tit];
            else
                title_arr[i].innerText = Dict.map[tit];
            title_arr[i].removeAttribute('title');
        }
        else {
            console.log("Can not translate ("+tit+")");
        }
    }
};

document.addEventListener("DOMContentLoaded", function(){
    Dict.translateAll();
});
